"""Generate the MoonBit test data for the efficient backdoor tests.

The upstream test suite keeps its example graphs in
`tests/causal_identifiers/example_graphs_efficient.py` as GML strings, together
with the adjustment sets the three efficient strategies have to produce. Hand
transcribing eleven graphs and their expected sets into MoonBit is a
transcription error waiting to happen, so this script parses the upstream file
and writes the graphs as edge lists together with the expected sets.

Run from the repository root:

    python _verify/gen_efficient_backdoor_testdata.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

UPSTREAM = Path(r"D:\src\MiniMax\git\dowhy\dowhy-0.14")
OUT = (
    Path(__file__).resolve().parent.parent
    / "src"
    / "identifiers"
    / "test_efficient_graphs.mbt"
)

sys.path.insert(0, str(UPSTREAM))
sys.path.insert(0, str(UPSTREAM / "tests"))

from tests.causal_identifiers.example_graphs_efficient import (  # noqa: E402
    TEST_EFFICIENT_BD_SOLUTIONS,
)


def parse_graph(graph_str: str) -> tuple[list[str], list[tuple[str, str]]]:
    """Return (nodes, edges) of a GML graph string."""
    nodes: list[str] = []
    edges: list[tuple[str, str]] = []
    for node in re.findall(r'node\[id "([^"]+)"', graph_str):
        nodes.append(node)
    for src, dst in re.findall(
        r'edge\[source "([^"]+)"\s+target "([^"]+)"', graph_str
    ):
        edges.append((src, dst))
    ordered: list[str] = []
    for node in nodes:
        if node not in ordered:
            ordered.append(node)
    return ordered, edges


def mbt_ident(name: str) -> str:
    """A MoonBit identifier built from a test case name."""
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def mbt_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def mbt_string_array(values) -> str:
    if not values:
        return "[]"
    return "[" + ", ".join(mbt_string(v) for v in values) + "]"


def mbt_optional_set(values) -> str:
    """A set of variables, or `None` when the upstream expects a failure."""
    if values is None:
        return "None"
    return "Some(" + mbt_string_array(sorted(values)) + ")"


def mbt_costs(costs) -> str:
    """The list of the costs of the variables."""
    if not costs:
        return "[]"
    entries = []
    for node, options in costs:
        entries.append("(" + mbt_string(node) + ", " + repr(float(options["cost"])) + ")")
    return "[" + ", ".join(entries) + "]"


def main() -> None:
    parts: list[str] = []
    parts.append("/// The example graphs of the efficient backdoor tests.")
    parts.append("///")
    parts.append("/// The graphs, the observed variables, the conditional variables, the")
    parts.append("/// costs and the expected adjustment sets come from")
    parts.append("/// `tests/causal_identifiers/example_graphs_efficient.py` of DoWhy 0.14.")
    parts.append("/// The file is generated by")
    parts.append("/// `_verify/gen_efficient_backdoor_testdata.py`; do not edit it by hand.")
    parts.append("")
    parts.append("/// One example graph with the adjustment sets it has to produce.")
    parts.append("pub struct EfficientTestCase {")
    parts.append("  nodes : Array[String]")
    parts.append("  edges : Array[String]")
    parts.append("  observed_nodes : Array[String]")
    parts.append("  conditional_nodes : Array[String]")
    parts.append("  costs : Array[(String, Double)]")
    parts.append("  efficient : Array[String]?")
    parts.append("  efficient_minimal : Array[String]?")
    parts.append("  efficient_mincost : Array[String]?")
    parts.append("}")
    parts.append("")
    parts.append("/// A new efficient backdoor test case.")
    parts.append("pub fn EfficientTestCase::new(")
    parts.append("  nodes : Array[String],")
    parts.append("  edges : Array[String],")
    parts.append("  observed_nodes : Array[String],")
    parts.append("  conditional_nodes : Array[String],")
    parts.append("  costs : Array[(String, Double)],")
    parts.append("  efficient : Array[String]?,")
    parts.append("  efficient_minimal : Array[String]?,")
    parts.append("  efficient_mincost : Array[String]?,")
    parts.append(") -> EfficientTestCase {")
    parts.append("  {")
    parts.append("    nodes,")
    parts.append("    edges,")
    parts.append("    observed_nodes,")
    parts.append("    conditional_nodes,")
    parts.append("    costs,")
    parts.append("    efficient,")
    parts.append("    efficient_minimal,")
    parts.append("    efficient_mincost,")
    parts.append("  }")
    parts.append("}")
    parts.append("")

    for name, solution in TEST_EFFICIENT_BD_SOLUTIONS.items():
        nodes, edges = parse_graph(solution["graph_str"])
        parts.append("/// The %s graph of the upstream test suite." % name)
        parts.append("fn efficient_case_%s() -> EfficientTestCase {" % mbt_ident(name))
        parts.append("  EfficientTestCase::new(")
        parts.append("    %s," % mbt_string_array(nodes))
        parts.append(
            "    %s," % mbt_string_array([f"{src}->{dst}" for src, dst in edges])
        )
        parts.append("    %s," % mbt_string_array(solution["observed_node_names"]))
        parts.append("    %s," % mbt_string_array(solution["conditional_node_names"]))
        parts.append("    %s," % mbt_costs(solution.get("costs")))
        parts.append("    %s," % mbt_optional_set(solution["efficient_adjustment"]))
        parts.append(
            "    %s," % mbt_optional_set(solution["efficient_minimal_adjustment"])
        )
        parts.append(
            "    %s," % mbt_optional_set(solution["efficient_mincost_adjustment"])
        )
        parts.append("  )")
        parts.append("}")
        parts.append("")

    parts.append("/// Every example graph of the upstream test suite.")
    parts.append("pub fn efficient_cases() -> Array[EfficientTestCase] {")
    parts.append("  [")
    for name in TEST_EFFICIENT_BD_SOLUTIONS:
        parts.append("    efficient_case_%s()," % mbt_ident(name))
    parts.append("  ]")
    parts.append("}")

    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT)
    print("cases:", len(TEST_EFFICIENT_BD_SOLUTIONS))


if __name__ == "__main__":
    main()
