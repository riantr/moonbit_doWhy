def parse_graph(graph_str):
    """Return (nodes, edges) of a GML or DOT graph string."""
    nodes = []
    edges = []
    for node in re.findall(r'node\[id "([^"]+)"', graph_str):
        nodes.append(node)
    for src, dst in re.findall(r'edge\[source "([^"]+)"\s+target "([^"]+)"', graph_str):
        edges.append((src, dst))
    if not nodes:
        # The DOT flavour: `digraph{A;B; A->B;}`.
        body = graph_str.split("{", 1)[1].rsplit("}", 1)[0]
        for part in body.split(";"):
            part = part.strip()
            if not part:
                continue
            if "->" in part:
                src, dst = part.split("->")
                src = src.strip()
                dst = dst.strip()
                nodes.extend([src, dst])
                edges.append((src, dst))
            else:
                nodes.append(part)
    ordered_nodes = []
    for node in nodes:
        if node not in ordered_nodes:
            ordered_nodes.append(node)
    return ordered_nodes, edges


def mbt_ident(name):
    """A MoonBit identifier built from a test case name."""
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def mbt_string(value):
    return '"' + value + '"'


def mbt_string_array(values):
    if not values:
        return "[]"
    return "[" + ", ".join(mbt_string(v) for v in values) + "]"


def mbt_set_array(sets):
    """A list of variable sets, each sorted and rendered as a string array."""
    if not sets:
        return "[]"
    rendered = []
    for entry in sets:
        rendered.append(mbt_string_array(sorted(entry)))
    return "[" + ", ".join(rendered) + "]"


def emit_case(name, solution, action, outcome, kind):
    nodes, edges = parse_graph(solution["graph_str"])
    lines = []
    lines.append("/// The %s graph of the upstream test suite." % name)
    lines.append("fn %s() -> IdentifierTestCase {" % mbt_ident(kind))
    lines.append("  IdentifierTestCase::new(")
    lines.append("    %s," % mbt_string_array(nodes))
    lines.append("    %s," % mbt_string_array([f"{src}->{dst}" for src, dst in edges]))
    lines.append("    %s," % mbt_string_array(action))
    lines.append("    %s," % mbt_string_array(outcome))
    lines.append("    %s," % mbt_string_array(solution["observed_variables"]))
    lines.append("    %s," % mbt_set_array(solution.get("biased_sets", [])))
    lines.append("    %s," % mbt_set_array(solution.get("minimal_adjustment_sets", [])))
    lines.append("    %s," % mbt_set_array(solution.get("maximal_adjustment_sets", [])))
    direct = solution.get("direct_maximal_adjustment_sets")
    if direct is None:
        direct = solution.get("maximal_adjustment_sets", [])
    lines.append("    %s," % mbt_set_array(direct))
    lines.append("  )")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


